/* WHAT A msgId PROMISES, ON BOTH OF THE CLIPS THIS ENGINE STORES.
 *
 * A msgId is the app's handle on a piece of audio: it draws a tick from one and
 * a play button from the other. Both are claims that the clip EXISTS, and this
 * file is about the engine handing out a msgId when it does not. The two halves
 * are the user's own recording and a spoken reply's TTS clip; they fail for the
 * same reason, through the same cacheAudio, and they cost different things.
 *
 * WHY THIS FILE EXISTS
 *
 * The app draws exactly one tick on a voice-note bubble and that tick means
 * "your recording cannot be lost". It is drawn when /user-audio answers with a
 * msgId. The handler used to answer the moment the bytes were in this process's
 * memory: cacheAudio fired `Bun.write(...).catch(console.error)` and never
 * waited for it, so the tick really meant "a write has been queued". Measured
 * against the live engine with a real clip, the response came at 23.24ms and the
 * file appeared at 23.27ms, which is why nobody ever saw it: it wins in
 * practice. It is not guaranteed, the failure went to a console the phone cannot
 * read, and once the hot cache evicts that msgId the only copy of the user's own
 * recording is gone.
 *
 * A user's recording is the one piece of audio in this system with no second
 * copy anywhere. The phone hands it over and forgets it.
 *
 * HOW THE FAILURE IS PRODUCED: by taking write permission off this test's own
 * audio directory, so the write fails for the same reason a full or read-only
 * disk would fail. No stub, no injected fault: the real Bun.write really does
 * refuse.
 *
 * -------------------------------------------------------------------------
 * ON REAL CAPTURES, AND WHY MOST OF THIS FILE NO LONGER DEMANDS ONE
 *
 * The old version of this file posted a REAL `.webm` out of <repo>/.run/audio
 * and refused to settle for generated audio, on the argument that this is a
 * test about a recording. That refusal is kept, and it is kept HONEST: the
 * capture-only tests below are `test.skipIf`-ed and say so loudly when the
 * store is empty (which is the state of every fresh checkout and of this box),
 * instead of failing seven tests for a reason that has nothing to do with the
 * engine.
 *
 * What DOES need real codec bytes is exactly one thing, and it is stated where
 * it is asserted: that the stored file is a decodable RECORDING, which is what
 * ffprobe reads a duration off and what the container/extension mapping is
 * for. Everything else here -- the ack ordering, the on-disk-before-announce
 * rule, msgId integrity, the traversal refusal, serving -- is about bytes
 * arriving and bytes coming back, and generated bytes prove it exactly as well.
 * Those run always.
 *
 * Nothing here writes to a real store: the wiring gets a throwaway data dir.
 */

