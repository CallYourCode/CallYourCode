/** Bytes that are NOT a recording: enough to prove a byte pipeline, and
 *  deliberately not enough to prove anything about audio. */
/* `Uint8Array<ArrayBuffer>`, not the bare `Uint8Array`: TS 5.7 reads the bare
 * name as Uint8Array<ArrayBufferLike>, and every comparison below is against
 * `new Uint8Array(await res.arrayBuffer())`, which is over a plain ArrayBuffer.
 * Two spellings of the same bytes will not compare. */
function generated(n = 4096): Uint8Array<ArrayBuffer> {
  const b = new Uint8Array(n);
  for (let i = 0; i < n; i++) b[i] = (i * 37 + 11) & 0xff;
  return b;
}

/* ------------------------------------------------------------------ the wiring */

let core: WireCore;
let voice: FakeVoice;
let http: ServedRoutes;
let client: FakeClient;
/** msgId -> was the clip on disk at the instant the `say` frame went out */
const onDiskAtSay = new Map<string, boolean>();

/* A DISK THAT WILL NOT TAKE THE CLIP, produced the way one really refuses.
 *
 * Freezing the audio directory itself does nothing: cacheAudio calls
 * mkdirPrivate() first, and mkdirPrivate chmods the leaf back to 0700 (it has
 * to: a recursive mkdir only sets the last component, and the umask on these
 * hosts is 0002). So the directory is REMOVED and its parent frozen, which is
 * the same thing a read-only or full disk does from inside cacheAudio: the
 * clip's directory cannot be made, and the write never happens.
 *
 * The parent is chosen so that only the CLIP's path is blocked. The words take
 * a different path and must still land, which is the whole distinction the TTS
 * half of this file draws. */
let locked: string | null = null;
async function freezeAudioDir(dir: string, parent: string): Promise<void> {
  await rm(dir, { recursive: true, force: true });
  await chmod(parent, 0o555);
  locked = parent;
}

beforeAll(async () => {
  /* "frames" is the layer that wires reply.ts, which is the speak half. The
   * clip store, the chat log and the session graph come with it; there is no
   * engine process, no Bun.serve for the wire and no voice engine but the fake
   * one below. */
  core = await wireCore({ with: ["frames"] });
  await until(() => core.sessions.size === 1, { what: "the pane to reconcile" });

  voice = fakeVoice({ ttsBytes: new Uint8Array([0xff, 0xfb, 0x90, 0x64, 0x00, 0x00]) });
  /* wireCore points tts.ts at a voice engine that REFUSES, so a seam test that
   * reaches for speech by accident fails loudly rather than dialling his actual
   * kokoro. This file is about speech, so it re-wires that one seam and nothing
   * else: same deps, same modules, the fake upstream instead of the refusal. */
  initTts({
    voiceUrl: () => voice.voiceUrl(),
    voiceFor: (id) => voiceFor(id),
    persistPatch: (id, mts, set, unset) => persistPatch(id, mts, set, unset),
    /* THE ONE SYNCHRONOUS OBSERVATION IN THIS FILE, and the only place "the
     * clip was on disk BEFORE it was announced" can honestly be asked: the say
     * frame is the announcement, and by the time a test could read the frame off
     * a client the write has long since finished either way. Checked here, in
     * the same tick the engine makes the claim. */
    broadcast: (m) => {
      const f = m as { t?: string; msgId?: string };
      if (f.t === "say" && f.msgId) {
        onDiskAtSay.set(f.msgId, existsSync(audioPath(f.msgId, "audio/mpeg")));
      }
      broadcast(m);
    },
    restoredChats: () => restoredChats,
    clock: core.clock,
  });

  http = serveRoutes({ groups: [mediaRoutes], ctx: { uploads: core.uploads! } });
  client = core.client({ attach: PANE });
  client.sock.data.sessionId = PANE; // the socket a session's MCP replies arrive on
});

afterAll(async () => {
  if (locked) { await chmod(locked, 0o755).catch(() => {}); locked = null; }
  http?.stop();
  voice?.stop();
  await core?.stop();
  resetTts();
  resetClips();
});

afterEach(async () => {
  // the permission goes back BEFORE anything else, or the next test writes into
  // a directory the previous one froze
  if (locked) { await chmod(locked, 0o755).catch(() => {}); locked = null; }
  client.clear();
  voice.reset();
});

const stagingAudio = () => join(core.dir, "staging", "audio");
