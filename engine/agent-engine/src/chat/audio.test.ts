/* ------------------------------------------------------- the real capture, if any
 *
 * Derived the way e2e/mutation/verified-run.sh derives it: --git-common-dir
 * points at the main checkout's .git from inside any linked worktree, so the
 * store is found whichever tree the suite is running from. READ ONLY; nothing
 * in this file writes to it or deletes from it. */
/* `Uint8Array<ArrayBuffer>` for the same reason `generated` says below: the
 * bare `Uint8Array` is Uint8Array<ArrayBufferLike> under TS 5.7, and every
 * comparison here is against bytes read out of an ArrayBuffer. */
async function realCapture(): Promise<Uint8Array<ArrayBuffer> | null> {
  const root = process.env.CYC_ENGINE_ROOT ??
    (await Bun.$`git rev-parse --path-format=absolute --git-common-dir`.cwd(import.meta.dir)
      .quiet().then((r) => join(r.stdout.toString().trim(), "..")).catch(() => ""));
  if (!root) return null;
  const dir = join(root, ".run", "audio");
  const webm = (await readdir(dir).catch(() => [] as string[]))
    .filter((n) => n.endsWith(".webm")).sort();
  if (!webm.length) {
    console.warn(
      `[audio.test] SKIPPING the real-capture tests: no .webm in ${dir}.\n` +
      "  Two assertions in this file are about a RECORDING rather than about bytes -- that " +
      "the stored clip is decodable (ffprobe reads a duration off it) and that a real " +
      "MediaRecorder container round-trips byte for byte through its own extension. " +
      "Generated audio cannot make either claim honestly, so they are skipped rather than " +
      "weakened. Record one from the app (press and hold the mic), or point CYC_ENGINE_ROOT " +
      "at a checkout whose .run/audio has one. Everything else in this file still runs.");
    return null;
  }
  // deterministic pick: the smallest non-empty one, so the test moves the fewest bytes
  let best = { name: webm[0], size: Infinity };
  for (const n of webm) {
    const size = Bun.file(join(dir, n)).size;
    if (size > 0 && size < best.size) best = { name: n, size };
  }
  return new Uint8Array(await readFile(join(dir, best.name)));
}

