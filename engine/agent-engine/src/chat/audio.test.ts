  expect(audioDirFor(String(say.msgId))).toContain("/agents/");

  const clip = await http.fetch(`/audio/${say.msgId}.mp3`);
  expect(clip.ok, "the announced clip does not serve").toBe(true);
  expect(new Uint8Array(await clip.arrayBuffer())).toEqual(new Uint8Array(voice.ttsBytes));
